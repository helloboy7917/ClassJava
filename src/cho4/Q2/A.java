package cho4.Q2;

public class A {
    public void print(){
        System.out.println("입력값이 없습니다.");
    }

    public void print(int i){
        System.out.println("정수입력 값:"+i);
    }

    public void print(double j){
        System.out.println("실수입력 값:"+j);
    }
    public void print(String k){
        System.out.println("문자열 입력값:"+k);
    }

}
